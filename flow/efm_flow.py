#!/usr/bin/env python3
r"""Build the demo flow as an EFM class flow, through EFM's Flow Designer API.

The spec is conf/config.yml (generated by flow/build_flow.py), so the bench flow and the class flow
are one flow. The @MINIFI_HOME@ and @WORK_DIR@ tokens are filled in from --home and --work: the EFM
deployer unpacks into <cwd>/nifi-minifi-cpp-2.26.09, so --home is that folder on the agent.

    export EFM_API=http://<efm-host>:10090/efm/api EFM_CLASS=MiNiFiCppDetect

    python3 flow/efm_flow.py plan  [--home H]     # write flow/efm-plan.json (positions) for check_layout.py
    python3 flow/efm_flow.py pin                  # pin the class's Designer palette to its agent manifest
    python3 flow/efm_flow.py build [--home H] [--max-seconds N]   # create CS, processors, connections (refuses a non-empty flow)
    python3 flow/efm_flow.py clear                # delete every connection, processor and CS (unpublished edits only)
    python3 flow/efm_flow.py set <processor> "<Property>=<value>" ...   # change properties in place: ids and ListFile state stay
    python3 flow/efm_flow.py validate
    python3 flow/efm_flow.py publish "<comment>"  # the push to the agent
    python3 flow/efm_flow.py show
    python3 flow/efm_flow.py export               # flow/<class>-flow-export.json

Layout (EFM Designer pitches, skill references/layout.md): vertical spine at x=0, row pitch 300.
ClassifyImage sits on the spine between extract-frames and detect. DetectObject fans out at the full branch
pitch: the drawing leg at x=-600, the JSON leg at x=+600.
Every failure goes to its own PutFile sink on its source's row, one branch pitch outboard on its
source's side. The EFM Designer has no label component, so there is no master label.
"""
import argparse
import json
import os
import sys
import urllib.request
import uuid
import yaml

EFM = os.environ.get("EFM_API", "http://localhost:10090/efm/api")
CLASS = os.environ.get("EFM_CLASS", "MiNiFiCppDetect")
HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "..", "conf", "config.yml")
EFM_HOME = os.environ.get("EFM_MINIFI_HOME", "/home/minifi/minifi-cpp-efm/nifi-minifi-cpp-2.26.09")
WORK_DIR = os.environ.get("WORK_DIR", "/tmp/minifi-detect")
ROW, BR = 300, 600
POS = {
    "list-clips": (0, 0), "extract-frames": (0, ROW), "classify": (0, 2 * ROW), "detect": (0, 3 * ROW),
    "draw": (-BR, 4 * ROW), "put-annotated": (-BR, 5 * ROW),
    "to-json": (BR, 4 * ROW), "json-name": (BR, 5 * ROW), "put-meta": (BR, 6 * ROW),
    "fail-extract-frames": (BR, ROW), "fail-classify": (BR, 2 * ROW), "fail-detect": (BR, 3 * ROW),
    "fail-draw": (-2 * BR, 4 * ROW), "fail-put-annotated": (-2 * BR, 5 * ROW),
    "fail-json-name": (2 * BR, 5 * ROW), "fail-put-meta": (2 * BR, 6 * ROW),
}


def call(method, path, body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(EFM + path, data=data, method=method, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            raw = r.read()
            return r.status, (json.loads(raw) if raw else None)
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode(errors="replace")


def load_spec(home, max_seconds=None, work=WORK_DIR):
    with open(SPEC) as f:
        spec = yaml.safe_load(f)
    txt = json.dumps(spec).replace("@MINIFI_HOME@", home).replace("@WORK_DIR@", work)
    spec = json.loads(txt)
    if max_seconds is not None:
        for p in spec["Processors"]:
            if p["name"] == "extract-frames":
                p["Properties"]["Max Seconds"] = str(max_seconds)
    missing = [p["name"] for p in spec["Processors"] if p["name"] not in POS]
    if missing:
        raise SystemExit(f"no position for {missing}: add them to POS")
    return spec


def pairs(spec):
    """One connection per (source, destination) pair, carrying every relationship between them."""
    by_id = {p["id"]: p["name"] for p in spec["Processors"]}
    out = {}
    for c in spec["Connections"]:
        k = (by_id[c["source id"]], by_id[c["destination id"]])
        out.setdefault(k, []).extend(c["source relationship names"])
    return out


def flow_ids():
    _, s = call("GET", "/designer/flows/summaries")
    for e in (s["elements"] if isinstance(s, dict) else s):
        if e.get("agentClass") == CLASS:
            return e["identifier"], e["rootProcessGroupIdentifier"]
    raise SystemExit(f"no designer flow for class {CLASS} yet (no agent has heartbeated?)")


def client_id():
    return call("GET", "/designer/client-identifier")[1]["clientId"]


def types(flow):
    """short name -> (fqcn, bundle) for processors and controller services in the class palette."""
    out = {}
    for kind in ("processors", "controller-services"):
        st, r = call("GET", f"/designer/flows/{flow}/types/{kind}")
        if st != 200:
            raise SystemExit(f"types/{kind}: {st} {r}")
        items = r.get("componentTypes", r) if isinstance(r, dict) else r
        for t in items:
            bundle = t.get("bundle") or {k: t[k] for k in ("group", "artifact", "version")}
            out[t["type"].rsplit(".", 1)[-1]] = (t["type"], bundle)
    return out


def plan(home, out_path):
    spec = load_spec(home)
    procs = [{"identifier": p["id"], "name": p["name"], "type": p["class"],
              "position": {"x": float(POS[p["name"]][0]), "y": float(POS[p["name"]][1])},
              "autoTerminatedRelationships": p["auto-terminated relationships list"]} for p in spec["Processors"]]
    ids = {p["name"]: p["id"] for p in spec["Processors"]}
    conns = [{"identifier": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{a}->{b}")), "name": "",
              "source": {"id": ids[a], "type": "PROCESSOR", "name": a},
              "destination": {"id": ids[b], "type": "PROCESSOR", "name": b},
              "selectedRelationships": rels, "bends": []} for (a, b), rels in pairs(spec).items()]
    doc = {"name": CLASS, "processors": procs, "connections": conns, "labels": [], "funnels": [],
           "inputPorts": [], "outputPorts": [], "processGroups": [], "remoteProcessGroups": []}
    with open(out_path, "w") as f:
        json.dump(doc, f, indent=1)
    print(f"wrote {out_path}: {len(procs)} processors, {len(conns)} connections")


def pin():
    _, cls = call("GET", f"/agent-classes/{CLASS}")
    mans = cls.get("agentManifests") or []
    if len(mans) != 1:
        raise SystemExit(f"class {CLASS} has manifests {mans}; expected exactly one")
    body = {"agentClassName": CLASS, "agentManifestId": mans[0]}
    st, r = call("POST", "/agent-class-manifest-config", body)
    if st == 409 or (isinstance(r, str) and "exists" in r):
        st, r = call("PUT", "/agent-class-manifest-config", body)
    print("pin", mans[0], st, r if st >= 300 else "")


def build(home, max_seconds=None, work=WORK_DIR):
    spec = load_spec(home, max_seconds, work)
    flow, pg = flow_ids()
    _, cur = call("GET", f"/designer/flows/{flow}")
    fc = cur["flowContent"]
    if fc.get("processors") or fc.get("connections") or fc.get("controllerServices"):
        raise SystemExit("the class flow is not empty; refusing to build on top of it")
    cid, tmap = client_id(), types(flow)
    need = {p["class"].rsplit(".", 1)[-1] for p in spec["Processors"]} | {c["class"] for c in spec["Controller Services"]}
    absent = sorted(need - set(tmap))
    if absent:
        raise SystemExit(f"not in the class palette: {absent} (manifest pinned? python processor loaded?)")

    cs_ids = {}
    for c in spec["Controller Services"]:
        fq, bundle = tmap[c["class"]]
        body = {"revision": {"version": 0, "clientId": cid}, "requestId": str(uuid.uuid4()),
                "componentConfiguration": {"componentType": "CONTROLLER_SERVICE", "type": fq, "bundle": bundle,
                                           "name": c["name"], "properties": c["Properties"]}}
        st, r = call("POST", f"/designer/flows/{flow}/process-groups/{pg}/controller-services", body)
        if st != 201:
            raise SystemExit(f"create CS {c['name']}: {st} {r}")
        cs_ids[c["name"]] = r["componentConfiguration"]["identifier"]
        print("created CS", c["name"], cs_ids[c["name"]])

    ids = {}
    for p in spec["Processors"]:
        fq, bundle = tmap[p["class"].rsplit(".", 1)[-1]]
        props = {k: cs_ids.get(v, v) if k == "Tract model service" else v for k, v in p["Properties"].items()}
        x, y = POS[p["name"]]
        body = {"revision": {"version": 0, "clientId": cid}, "requestId": str(uuid.uuid4()),
                "componentConfiguration": {
                    "componentType": "PROCESSOR", "type": fq, "bundle": bundle, "name": p["name"],
                    "position": {"x": float(x), "y": float(y)}, "properties": props,
                    "schedulingStrategy": p["scheduling strategy"], "schedulingPeriod": p["scheduling period"],
                    "autoTerminatedRelationships": p["auto-terminated relationships list"]}}
        st, r = call("POST", f"/designer/flows/{flow}/process-groups/{pg}/processors", body)
        if st != 201:
            raise SystemExit(f"create {p['name']}: {st} {r}")
        ids[p["name"]] = r["componentConfiguration"]["identifier"]
        print("created", p["name"], fq, ids[p["name"]])

    for (a, b), rels in pairs(spec).items():
        body = {"revision": {"version": 0, "clientId": cid}, "requestId": str(uuid.uuid4()),
                "componentConfiguration": {
                    "componentType": "CONNECTION", "name": "",
                    "source": {"id": ids[a], "type": "PROCESSOR", "groupId": pg},
                    "destination": {"id": ids[b], "type": "PROCESSOR", "groupId": pg},
                    "selectedRelationships": rels, "bends": [],
                    "backPressureObjectThreshold": 2000, "backPressureDataSizeThreshold": "512 MB",
                    "flowFileExpiration": "0 sec"}}
        st, r = call("POST", f"/designer/flows/{flow}/process-groups/{pg}/connections", body)
        if st != 201:
            raise SystemExit(f"connect {a}->{b}: {st} {r}")
        print("connected", a, "->", b, rels)


def clear():
    flow, _ = flow_ids()
    cid = client_id()
    fc = call("GET", f"/designer/flows/{flow}")[1]["flowContent"]
    for kind, items in (("connections", fc.get("connections", [])), ("processors", fc.get("processors", [])),
                        ("controller-services", fc.get("controllerServices", []))):
        for c in items:
            ver = call("GET", f"/designer/flows/{flow}/{kind}/{c['identifier']}")[1]["revision"]["version"]
            st, _ = call("DELETE", f"/designer/flows/{flow}/{kind}/{c['identifier']}?version={ver}&clientId={cid}")
            print("deleted", kind, c.get("name") or c["identifier"], st)


def set_props(name, assigns):
    """Change properties of one processor in the Designer draft, in place (PUT with its revision), so
    its id and the agent-side state keyed on it (ListFile's listing) survive the publish. Refuses a
    processor with any sensitive property: a GET returns it masked and a PUT would write the mask back."""
    flow, _ = flow_ids()
    fc = call("GET", f"/designer/flows/{flow}")[1]["flowContent"]
    match = [p for p in fc.get("processors", []) if p["name"] == name]
    if len(match) != 1:
        raise SystemExit(f"{len(match)} processors named {name!r}")
    pid = match[0]["identifier"]
    st, ent = call("GET", f"/designer/flows/{flow}/processors/{pid}")
    if st != 200:
        raise SystemExit(f"GET {name}: {st} {ent}")
    cc = ent["componentConfiguration"]
    sens = [k for k, d in (ent.get("componentDefinition", {}).get("propertyDescriptors") or {}).items() if d.get("sensitive")]
    if sens or any(v == "********" for v in (cc.get("properties") or {}).values()):
        raise SystemExit(f"{name} has sensitive properties {sens}; not doing a full-entity PUT")
    props = dict(cc.get("properties") or {})
    for kv in assigns:
        k, v = kv.split("=", 1)
        if k not in props:
            raise SystemExit(f"{name} has no property {k!r} (has {sorted(props)})")
        print(f"{name}: {k} {props[k]!r} -> {v!r}")
        props[k] = v
    body = {"revision": {"version": ent["revision"]["version"], "clientId": client_id()},
            "requestId": str(uuid.uuid4()),
            "componentConfiguration": {"identifier": pid, "componentType": "PROCESSOR", "properties": props}}
    st, r = call("PUT", f"/designer/flows/{flow}/processors/{pid}", body)
    if st != 200:
        raise SystemExit(f"PUT {name}: {st} {r}")
    got = r["componentConfiguration"]["properties"]
    bad = {k: got.get(k) for kv in assigns for k in [kv.split("=", 1)[0]] if got.get(k) != kv.split("=", 1)[1]}
    print("updated (draft; publish pushes it)" if not bad else f"PUT returned but not applied: {bad}")


def show():
    flow, _ = flow_ids()
    fc = call("GET", f"/designer/flows/{flow}")[1]["flowContent"]
    names = {p["identifier"]: p["name"] for p in fc.get("processors", [])}
    for c in fc.get("controllerServices", []):
        print("CS  ", c["name"], c["type"], json.dumps(c.get("properties", {})))
    for p in fc.get("processors", []):
        print("PROC", p["name"], p["type"], p["position"], p.get("schedulingPeriod"), p.get("autoTerminatedRelationships"))
    for c in fc.get("connections", []):
        print("CONN", names.get(c["source"]["id"]), "->", names.get(c["destination"]["id"]), c["selectedRelationships"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["plan", "pin", "build", "clear", "set", "validate", "publish", "show", "export"])
    ap.add_argument("comment", nargs="?", default="frames -> ClassifyImage -> DetectObject -> DrawBoundingBox",
                    help="publish: the comment; set: the processor name")
    ap.add_argument("assign", nargs="*", help="set: Property=value pairs")
    ap.add_argument("--home", default=EFM_HOME, help="MINIFI_HOME on the agent (the deployer's install folder)")
    ap.add_argument("--work", default=WORK_DIR, help="the work folder on the agent: clips/, out/, meta/, fail/")
    ap.add_argument("--max-seconds", type=int, help="override ExtractVideoFrames' Max Seconds (first run: 10)")
    a = ap.parse_args()
    if a.cmd == "plan":
        plan(a.home, os.path.join(HERE, "efm-plan.json"))
    elif a.cmd == "pin":
        pin()
    elif a.cmd == "clear":
        clear()
    elif a.cmd == "set":
        set_props(a.comment, a.assign)
    elif a.cmd == "build":
        build(a.home, a.max_seconds, a.work)
    elif a.cmd == "validate":
        flow, _ = flow_ids()
        st, r = call("GET", f"/designer/flows/{flow}/validate")
        print(st, json.dumps(r, indent=1))
        sys.exit(0 if st == 200 and not (r or {}).get("validationErrors") else 1)
    elif a.cmd == "publish":
        flow, _ = flow_ids()
        st, r = call("POST", f"/designer/flows/{flow}/publish", {"comments": a.comment})
        print(st, r if st >= 300 else "published")
    elif a.cmd == "show":
        show()
    elif a.cmd == "export":
        st, r = call("GET", f"/designer/{CLASS}/flows/export")
        path = os.path.join(HERE, f"{CLASS}-flow-export.json")
        with open(path, "w") as f:
            json.dump(r, f, indent=1)
        print(st, "wrote", path)


if __name__ == "__main__":
    main()
